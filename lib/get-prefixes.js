import fs from "node:fs";

const VERSION = "7.x";

async function getPrefixes() {
	let url = "https://api.fontawesome.com";

	let data = await fetch(url, {
		method: "post",
		body: JSON.stringify({
			"query": `query { release(version:"${VERSION}"){ version familyStyles { prefix family style } } }`
		}),
		headers: {
			"Content-Type": "application/json",
		},
	});

	let json = await data.json();
	// console.log( JSON.stringify(json, null, 2) );

	let familyStyleToPrefixMap = {};
	let prefixToFamilyStyleMap = {};
	let styles = new Set();
	let families = new Set();
	let prefixes = new Set();

	let familyStyles = json?.data?.release?.familyStyles;
	if(!Array.isArray(familyStyles) || familyStyles.length === 0) {
		throw new Error("No family styles returned from the Font Awesome API: " + JSON.stringify(json));
	}

	for(let {family, prefix, style} of familyStyles) {
		styles.add(style);
		families.add(family);
		prefixes.add(prefix);

		if(!prefixToFamilyStyleMap[prefix]) {
			prefixToFamilyStyleMap[prefix] = {
				family,
				style,
			};
		}

		if(!familyStyleToPrefixMap[family]) {
			familyStyleToPrefixMap[family] = {};
		}
		if(!familyStyleToPrefixMap[family][style]) {
			familyStyleToPrefixMap[family][style] = prefix;
		}
	}

	return {
		version: json.data.release.version,
		prefixes: Array.from(prefixes),
		styles: Array.from(styles),
		families: Array.from(families),
		familyStyleToPrefixMap,
		prefixToFamilyStyleMap,
	};
};

let { version, ...prefixes } = await getPrefixes();
let filePath = "./src/prefixes.js";
fs.writeFileSync(filePath, `// Warning: this file is automatically generated by \`npm run update-prefixes\` (Font Awesome API release ${version})
export default ${JSON.stringify(prefixes, null, 2)}`);
console.log( `Prefixes written to ${filePath}.` );